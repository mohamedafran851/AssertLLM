from pathlib import Path
import json
from llm_client import generate

PROJECT_DIR = Path(__file__).resolve().parent.parent

rtl_file = PROJECT_DIR / "rtl" / "alu4.v"
spec_file = PROJECT_DIR / "prompts" / "alu4_spec.txt"

rtl_code = rtl_file.read_text()
specification = spec_file.read_text()

print("===== AssertLLM ALU GENERATOR =====")
print("RTL loaded!")
print("Specification loaded!")

prompt = f"""
You are an expert SystemVerilog Design Verification Engineer.

Generate exactly SEVEN meaningful SystemVerilog assertions
for the following 4-bit combinational ALU.

RTL:
{rtl_code}

SPECIFICATION:
{specification}

TESTBENCH:
- clk is generated by the testbench.
- Inputs are applied before the positive clock edge.
- Outputs settle before the positive clock edge.
- Assertions sample outputs at posedge clk.

CRITICAL ASSERTION LOGIC:

The antecedent (left side of |->) MUST contain ONLY
the operation selector condition.

The consequent (right side of |->) MUST check the
expected output values.

CORRECT EXAMPLE:

property example_add;
    @(posedge clk)
    (ALU_Sel == 3'b000)
    |->
    ({{CarryOut, ALU_Out}} ==
     ({{1'b0, A}} + {{1'b0, B}}));
endproperty

assert property (example_add);

INCORRECT EXAMPLE - NEVER GENERATE THIS:

(ALU_Sel == 3'b000 && ALU_Out == expected_value)
|->
(1'b1);

This is vacuous checking and is NOT acceptable.

REQUIRED ASSERTIONS:

1. ADD:
Name: alu_add_property
Antecedent: ALU_Sel == 3'b000
Consequent:
{{CarryOut, ALU_Out}} ==
({{1'b0, A}} + {{1'b0, B}})

2. SUB:
Name: alu_sub_property
Antecedent: ALU_Sel == 3'b001
Consequent:
{{CarryOut, ALU_Out}} ==
({{1'b0, A}} - {{1'b0, B}})

3. AND:
Name: alu_and_property
Antecedent: ALU_Sel == 3'b010
Consequent:
(ALU_Out == (A & B)) && (CarryOut == 1'b0)

4. OR:
Name: alu_or_property
Antecedent: ALU_Sel == 3'b011
Consequent:
(ALU_Out == (A | B)) && (CarryOut == 1'b0)

5. XOR:
Name: alu_xor_property
Antecedent: ALU_Sel == 3'b100
Consequent:
(ALU_Out == (A ^ B)) && (CarryOut == 1'b0)

6. NOT:
Name: alu_not_property
Antecedent: ALU_Sel == 3'b101
Consequent:
(ALU_Out == (~A)) && (CarryOut == 1'b0)

7. INVALID:
Name: alu_invalid_property
Antecedent:
((ALU_Sel == 3'b110) || (ALU_Sel == 3'b111))
Consequent:
(ALU_Out == 4'b0000) && (CarryOut == 1'b0)

STRICT RULES:
- Generate exactly seven assertions.
- Use the exact property names listed above.
- Use |-> for every assertion.
- Use the operation selector ONLY in the antecedent.
- Put all output checks in the consequent.
- Never use 1'b1 as a consequent.
- Never put expected output checks in the antecedent.
- Use parentheses around bitwise expressions.
- Check CarryOut in every operation.
- Do not use |=> or $past.
- Do not use reset.
- Do not generate clock or RTL code.
- Do not generate comments instead of assertions.

OUTPUT FORMAT:
Return valid JSON only.
Use this structure:

{{
  "assertions": [
    {{
      "name": "alu_add_property",
      "code": "complete SystemVerilog assertion code"
    }}
  ]
}}

The assertions array must contain exactly seven objects,
in the required order.
Each object must contain name and code.
"""

print("\nGenerating ALU assertions using the selected local LLM...")

raw_response = generate(prompt)
raw_file = PROJECT_DIR / "reports" / "alu4_llm_raw_response.txt"
raw_file.parent.mkdir(exist_ok=True)
raw_file.write_text(raw_response)

print("\n===== RAW LLM RESPONSE SAVED =====")
print(raw_response)
try:
    data = json.loads(raw_response)

    assertions = data["assertions"]

    expected_names = [
        "alu_add_property",
        "alu_sub_property",
        "alu_and_property",
        "alu_or_property",
        "alu_xor_property",
        "alu_not_property",
        "alu_invalid_property"
    ]

    if not isinstance(assertions, list) or len(assertions) != 7:
        raise ValueError("Expected exactly seven assertions.")

    assertion_codes = []
    received_names = []

    for item in assertions:

        if not isinstance(item, dict):
            raise ValueError("Invalid assertion entry.")

        name = item.get("name")
        code = item.get("code")

        if not isinstance(name, str) or not name.strip():
            raise ValueError("Assertion name missing.")

        if not isinstance(code, str) or not code.strip():
            raise ValueError(f"Assertion code missing: {name}")

        received_names.append(name.strip())
        assertion_codes.append(code.strip())

    if received_names != expected_names:
        raise ValueError(
            f"Unexpected assertion names or order: {received_names}"
        )

    output_file = PROJECT_DIR / "generated" / "alu4_assertions.sv"
    report_file = PROJECT_DIR / "reports" / "alu4_llm_response.json"

    output_file.parent.mkdir(exist_ok=True)
    report_file.parent.mkdir(exist_ok=True)

    report_file.write_text(json.dumps(data, indent=4))
    output_file.write_text("\n\n".join(assertion_codes) + "\n")

    print("\nJSON parsing successful!")
    print("Assertions generated:", len(assertion_codes))
    print("Generated SVA:", output_file)
    print("AI response:", report_file)

except (json.JSONDecodeError, KeyError, TypeError, ValueError) as error:

    print("\nAI OUTPUT VALIDATION FAILED!")
    print("Reason:", error)
    print("Previous assertion file was not overwritten.")
